// Vendors the mapped icons into the web app and emits its lookup tables from
// assets/languages.json. Two artifacts, both generated:
//
//   apps/web/src/assets/extension-icons/*.svg — copies of exactly the icons the
//   map references, nothing more. One shared folder: glyphs and brands cannot
//   collide, every devicon name carries an `-original` suffix;
//   apps/web/src/lib/icons.gen.ts — the tables, importing those files so the
//   bundler owns their URLs.
//
// Files rather than inlined markup on purpose: several devicon files declare
// the same gradient ids ("a", "b"), which would collide the moment two of them
// shared a document. As separate assets they never meet.
// Run: dart run bin/icons/emit_web_icons.dart
import 'dart:convert';
import 'dart:io';

/// Where the vendored copies land, relative to the package root.
const iconsPath = '../apps/web/src/assets/extension-icons';

/// Where the tables land, and how they reach [iconsPath] from there.
const emitPath = '../apps/web/src/lib/icons.gen.ts';
const importPath = '../assets/extension-icons';

/// Source folder under assets/icons/ for each icon kind, and its emitted map.
const folders = {'slug': 'simple-icons', 'devicon': 'dev-icons'};

/// The Phosphor icon a name the map does not cover is drawn with. Emitted as a
/// spec of its own, so a lookup always resolves to something drawable and the
/// renderer never carries a branch for the miss. Seeded into the emitted
/// `PhosphorIcon` union whether or not the map itself reaches for it.
const fallback = 'file';

void main() {
  // Script lives in bin/icons/; resolve everything against the package root.
  final root = File.fromUri(Platform.script).parent.parent.parent.absolute.path;
  final doc = jsonDecode(File('$root/assets/languages.json').readAsStringSync()) as Map<String, dynamic>;

  // Collect what the map actually references, per kind.
  final referenced = {for (final kind in folders.keys) kind: <String>{}};
  final phosphor = <String>{fallback};
  for (final section in doc.values) {
    for (final spec in (section as Map<String, dynamic>).values) {
      (spec as Map<String, dynamic>).forEach((key, value) {
        if (folders.containsKey(key)) {
          referenced[key]!.add(value as String);
        } else if (key == 'phosphor') {
          phosphor.add(value as String);
        }
      });
    }
  }

  // Nothing is emitted until every referenced file is accounted for.
  final missing = [
    for (final kind in folders.keys)
      for (final name in referenced[kind]!)
        if (!File('$root/assets/icons/${folders[kind]}/$name.svg').existsSync()) '${folders[kind]}/$name.svg',
  ];
  if (missing.isNotEmpty) {
    stderr.writeln('missing source icons:\n  ${missing.join('\n  ')}');
    exit(1);
  }

  // Rebuilt from scratch, so an icon dropped from the map stops being vendored.
  final target = Directory('$root/$iconsPath');
  if (target.existsSync()) {
    target.deleteSync(recursive: true);
  }
  target.createSync(recursive: true);
  var copied = 0;
  folders.forEach((kind, folder) {
    for (final name in referenced[kind]!) {
      File('$root/assets/icons/$folder/$name.svg').copySync('${target.path}/$name.svg');
      copied++;
    }
  });

  File('$root/$emitPath')
    ..createSync(recursive: true)
    ..writeAsStringSync(emit(doc, referenced, phosphor));
  final keys = doc.values.fold(0, (sum, section) => sum + (section as Map<String, dynamic>).length);
  print('icons: $keys keys, $copied svgs -> ${iconsPath.substring(3)}/, tables -> ${emitPath.substring(3)}');
}

/// The whole `icons.gen.ts`: types, one import per vendored file, then a table
/// per section.
String emit(Map<String, dynamic> doc, Map<String, Set<String>> referenced, Set<String> phosphor) {
  final names = sorted(phosphor).map(quote).join(' | ');
  final buffer = StringBuffer()
    ..writeln(
      '// Generated by `dart run bin/icons/emit_web_icons.dart` from tools/assets/languages.json — do not edit.',
    )
    ..writeln();

  // `?no-inline` on every one: the sprite is a single string naming each asset by URL, so anything Vite inlines rides
  // in the initial JS chunk whether or not a file of that type is ever on screen. 133 of these clear the 4 KB
  // `assetsInlineLimit` default, which cost 57 KB gzipped. As files they are fetched only when a `<symbol>` is
  // actually `<use>`d. `apps/web` pins this in `icons.test.ts`.
  for (final kind in folders.keys) {
    for (final name in sorted(referenced[kind]!)) {
      buffer.writeln("import ${identifier(kind, name)} from '$importPath/$name.svg?no-inline';");
    }
  }

  buffer
    ..writeln('/**')
    ..writeln(' * How one file gets drawn. `glyph` is a monochrome brand mark to be painted in')
    ..writeln(' * its tint; `brand` carries its own colors and takes none; `letters` is the')
    ..writeln(' * tile that stands in where a language has no mark; `phosphor` is a media kind.')
    ..writeln(' * The last two carry a tint only when the language has a color of its own — a')
    ..writeln(" * `null` tint means the theme's ink, not a missing value.")
    ..writeln(' */')
    ..writeln('  ')
    ..writeln('export type FileIconSpec =')
    ..writeln("  | { kind: 'glyph'; src: string; tint: IconTint }")
    ..writeln("  | { kind: 'brand'; src: string }")
    ..writeln("  | { kind: 'phosphor'; name: PhosphorIcon; tint: IconTint | null }")
    ..writeln("  | { kind: 'letters'; letters: string; tint: IconTint | null };")
    ..writeln()
    ..writeln("/** A brand color already clamped to 3:1 against each theme's surfaces. */")
    ..writeln('export interface IconTint {')
    ..writeln('  light: string;')
    ..writeln('  dark: string;')
    ..writeln('}')
    ..writeln()
    ..writeln('/** The Phosphor icons the map draws from, and the fallback, by name. */')
    ..writeln('export type PhosphorIcon = $names;')
    ..writeln()
    ..writeln('/** What a name neither table covers is drawn with. */')
    ..writeln("export const FALLBACK_ICON: FileIconSpec = { kind: 'phosphor', name: ${quote(fallback)}, tint: null };")
    ..writeln();

  const tables = {'names': 'FILENAME_ICONS', 'extensions': 'EXTENSION_ICONS'};
  for (final MapEntry(key: section, value: constant) in tables.entries) {
    final entries = doc[section] as Map<String, dynamic>;
    buffer
      ..writeln()
      ..writeln('export const $constant: Record<string, FileIconSpec> = {');
    for (final key in sorted(entries.keys)) {
      buffer.writeln('  ${quote(key)}: ${literal(entries[key] as Map<String, dynamic>)},');
    }
    buffer.writeln('};');
  }
  return buffer.toString();
}

/// One `FileIconSpec` literal, on a single line — the artifact is generated and
/// Biome-excluded, so it is written to diff by entry rather than to be read.
String literal(Map<String, dynamic> spec) {
  final tint = switch (spec['color']) {
    final Map<String, dynamic> color =>
      '{ light: ${quote(color['light'] as String)}, '
          'dark: ${quote(color['dark'] as String)} }',
    _ => 'null',
  };

  return switch (spec) {
    {'slug': final String slug} => "{ kind: 'glyph', src: ${identifier('slug', slug)}, tint: $tint }",
    {'devicon': final String brand} => "{ kind: 'brand', src: ${identifier('devicon', brand)} }",
    {'phosphor': final String name} => "{ kind: 'phosphor', name: ${quote(name)}, tint: $tint }",
    _ => "{ kind: 'letters', letters: ${quote(spec['letterform'] as String)}, tint: $tint }",
  };
}

/// The import binding for a vendored file: `dart-original` -> `dartOriginalBrand`,
/// `gnubash` -> `gnubashGlyph`. Suffixed so the two kinds cannot collide.
String identifier(String kind, String name) {
  final parts = name.split(RegExp('[-_.]'));
  final camel = parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
  return '$camel${kind == 'slug' ? 'Glyph' : 'Brand'}';
}

List<String> sorted(Iterable<String> values) => values.toList()..sort();

/// A single-quoted TS string literal — the repo's Biome quote style.
String quote(String value) => "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";
