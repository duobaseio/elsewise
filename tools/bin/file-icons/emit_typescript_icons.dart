// Vendors the icons in assets/languages.json into the components package and emits their lookup tables.
import 'dart:convert';
import 'dart:io';

import 'package:elsewise_tool/src/tints.dart';

const iconsPath = '../packages/components/src/assets/file-icons';
const emitPath = '../packages/components/src/lib/file-icons.gen.ts';
const importPath = '../assets/file-icons';

const folders = {'slug': 'simple-icons', 'devicon': 'dev-icons'};
const kinds = ['slug', 'devicon', 'phosphor', 'letterform'];
const fallbackIcon = 'file';

void main() {
  final root = File.fromUri(Platform.script).parent.parent.parent.absolute.path;
  final map = File('$root/assets/languages.json');
  final doc = jsonDecode(map.readAsStringSync()) as Map<String, dynamic>;

  final referenced = {for (final kind in folders.keys) kind: <String>{}};
  final phosphor = <String>{fallbackIcon};
  final problems = <String>[];
  for (final MapEntry(key: section, value: specs) in doc.entries) {
    for (final MapEntry(:key, value: spec) in (specs as Map<String, dynamic>).entries) {
      final found = problemsOf(spec as Map<String, dynamic>);
      if (found.isNotEmpty) {
        problems.addAll(found.map((problem) => '$section.$key: $problem'));
        continue;
      }
      spec.forEach((key, value) {
        if (folders.containsKey(key)) {
          referenced[key]!.add(value as String);
        } else if (key == 'phosphor') {
          phosphor.add(value as String);
        }
      });
    }
  }

  // Both kinds are vendored into one flat folder.
  for (final name in referenced['slug']!.intersection(referenced['devicon']!)) {
    problems.add('$name.svg: named by both a slug and a devicon');
  }
  for (final kind in folders.keys) {
    for (final name in referenced[kind]!) {
      if (!File('$root/assets/file-icons/${folders[kind]}/$name.svg').existsSync()) {
        problems.add('${folders[kind]}/$name.svg: missing source icon');
      }
    }
  }

  if (problems.isNotEmpty) {
    stderr.writeln('nothing emitted:\n  ${problems.join('\n  ')}');
    exit(1);
  }

  final tints = resolveTints(doc);
  map.writeAsStringSync('${const JsonEncoder.withIndent('  ').convert(doc)}\n');
  print('tints: ${tints['clamped']} clamped, ${tints['inverted']} inverted, ${tints['unmoved']} already clear');

  final target = Directory('$root/$iconsPath');
  if (target.existsSync()) {
    target.deleteSync(recursive: true);
  }
  target.createSync(recursive: true);
  var copied = 0;
  folders.forEach((kind, folder) {
    for (final name in referenced[kind]!) {
      File('$root/assets/file-icons/$folder/$name.svg').copySync('${target.path}/$name.svg');
      copied++;
    }
  });

  File('$root/$emitPath')
    ..createSync(recursive: true)
    ..writeAsStringSync(emit(doc, referenced, phosphor));
  final keys = doc.values.fold(0, (sum, section) => sum + (section as Map<String, dynamic>).length);
  print('icons: $keys keys, $copied svgs -> ${iconsPath.substring(3)}/, tables -> ${emitPath.substring(3)}');
}

String emit(Map<String, dynamic> doc, Map<String, Set<String>> referenced, Set<String> phosphor) {
  final names = sorted(phosphor).map(quote).join(' | ');
  final buffer = StringBuffer()
    ..writeln(
      '// Generated by `dart run bin/file-icons/emit_typescript_icons.dart` from tools/assets/languages.json — do not edit.',
    )
    ..writeln();

  // `?no-inline` keeps Vite from inlining every icon into the initial JS chunk as a `data:` URI.
  for (final kind in folders.keys) {
    for (final name in sorted(referenced[kind]!)) {
      buffer.writeln("import ${identifier(kind, name)} from '$importPath/$name.svg?no-inline';");
    }
  }

  buffer
    ..writeln()
    ..writeln('/**')
    ..writeln(' * A file icon, one of:')
    ..writeln(' * - `glyph`: a monochrome mark, painted in its tint.')
    ..writeln(' * - `brand`: a brand icon in its original colors.')
    ..writeln(" * - `phosphor`: a Phosphor icon whose color defaults to the theme's ink.")
    ..writeln(" * - `letters`: one to three letters whose color defaults to the theme's ink.")
    ..writeln(' */')
    ..writeln('export type FileIconData =')
    ..writeln("  | { kind: 'glyph'; src: string; tint: IconTint }")
    ..writeln("  | { kind: 'brand'; src: string }")
    ..writeln("  | { kind: 'phosphor'; name: $names; tint: IconTint | null }")
    ..writeln("  | { kind: 'letters'; letters: string; tint: IconTint | null };")
    ..writeln()
    ..writeln('/**')
    ..writeln(" * An icon's CSS colors in light and dark variants.")
    ..writeln(' */')
    ..writeln('export interface IconTint {')
    ..writeln('  light: string;')
    ..writeln('  dark: string;')
    ..writeln('}')
    ..writeln()
    ..writeln(
      "export const FALLBACK_FILE_ICON: FileIconData = { kind: 'phosphor', name: ${quote(fallbackIcon)}, tint: null };",
    );

  const tables = {'names': 'FILENAME_ICONS', 'extensions': 'EXTENSION_ICONS'};
  for (final MapEntry(key: section, value: constant) in tables.entries) {
    final entries = doc[section] as Map<String, dynamic>;
    buffer
      ..writeln()
      ..writeln('export const $constant: Record<string, FileIconData> = {');
    for (final key in sorted(entries.keys)) {
      buffer.writeln('  ${quote(key)}: ${literal(entries[key] as Map<String, dynamic>)},');
    }
    buffer.writeln('};');
  }
  return buffer.toString();
}

List<String> problemsOf(Map<String, dynamic> spec) {
  final keys = spec.keys.where((key) => key != 'color').toList();
  if (keys.length != 1 || !kinds.contains(keys.single)) {
    return ['needs exactly one of ${kinds.join(', ')}'];
  }

  final kind = keys.single;
  final value = spec[kind];
  final color = spec['color'];
  return [
    if (value is! String || value.isEmpty) '`$kind` must be a non-empty string',
    if (kind == 'letterform' && value is String && value.length > 3) 'a letterform is one to three characters',
    if (kind == 'slug' && color == null) 'a slug needs a `color`',
    if (kind == 'devicon' && color != null) 'a devicon takes no `color`',
    if (color != null &&
        !(color is Map<String, dynamic> && color.length == 2 && color['light'] is String && color['dark'] is String))
      '`color` needs `light` and `dark`, and nothing else',
  ];
}

String literal(Map<String, dynamic> spec) {
  final tint = switch (spec['color']) {
    final Map<String, dynamic> color =>
      '{ light: ${quote(color['light'] as String)}, '
          'dark: ${quote(color['dark'] as String)} }',
    _ => 'null',
  };

  return switch (spec) {
    {'slug': final String slug} => "{ kind: 'glyph', src: ${identifier('slug', slug)}, tint: $tint }",
    {'devicon': final String brand} => "{ kind: 'brand', src: ${identifier('devicon', brand)} }",
    {'phosphor': final String name} => "{ kind: 'phosphor', name: ${quote(name)}, tint: $tint }",
    _ => "{ kind: 'letters', letters: ${quote(spec['letterform'] as String)}, tint: $tint }",
  };
}

/// `dart-original` -> `dartOriginalBrand`, `gnubash` -> `gnubashGlyph`, `1password` -> `_1passwordGlyph`.
String identifier(String kind, String name) {
  final parts = name.split(RegExp('[^A-Za-z0-9]+')).where((p) => p.isNotEmpty).toList();
  final camel = parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
  final prefix = camel.startsWith(RegExp('[0-9]')) ? '_' : '';
  return '$prefix$camel${kind == 'slug' ? 'Glyph' : 'Brand'}';
}

List<String> sorted(Iterable<String> values) => values.toList()..sort();

String quote(String value) => "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";
