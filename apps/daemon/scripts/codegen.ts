import fs from 'node:fs/promises';
import path from 'node:path';
import { generate, SqliteDialect } from 'kysely-codegen';
import { openDatabase } from '../src/database/database';
import type { Migration } from '../src/database/migrate';

/** Generates the migrations in `src/gen/migrations.ts` */

const root = path.resolve(import.meta.dirname, '..');
const migrationsDirectory = path.join(root, 'database', 'migrations');
const gen = path.join(root, 'src', 'gen');

const names = (await fs.readdir(migrationsDirectory)).filter((name) => name.endsWith('.sql')).sort();
const migrations: Migration[] = [];
for (const name of names) {
  const sql = await fs.readFile(path.join(migrationsDirectory, name), 'utf8');
  const stem = path.basename(name, '.sql');
  const separator = stem.indexOf('_');
  if (separator === -1) {
    throw new Error(`Migration ${name} is not named <version>_<description>.sql.`);
  }
  migrations.push({ version: stem.slice(0, separator), description: stem.slice(separator + 1), sql });
}

await fs.mkdir(gen, { recursive: true });
await fs.writeFile(
  path.join(gen, 'migrations.ts'),
  [
    '/*',
    ' * Generated by scripts/codegen.ts from database/migrations.',
    ' * Do not edit.',
    ' */',
    '',
    "import type { Migration } from '../database/migrate';",
    '',
    '/** Database migrations sorted by oldest first. */',
    `export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};`,
    '',
  ].join('\n'),
);

/** Generate kysely types with kysely-codegen. Stored in `src/gen/database.ts`. */

const db = openDatabase(':memory:', migrations);
try {
  await generate({
    db,
    dialect: new SqliteDialect(),
    outFile: path.join(gen, 'database.ts'),
    excludePattern: 'schema_revision',
  });
} finally {
  await db.destroy();
}
